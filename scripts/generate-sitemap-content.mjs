#!/usr/bin/env node
/**
 * 生成 src/generated/sitemap-content.ts
 *
 * 把 public/robots.txt 和 public/sitemap-image.xml 的内容嵌入为 TypeScript
 * 字符串导出,供 Edge Runtime route handler 静态 import。
 *
 * 为什么:CF Pages Functions / Edge Runtime 不支持 node:fs,
 *  webpack ?raw 也需要额外的 loader 配置。最简单的解法是
 *  build 时把内容读出来,生成 .ts 文件,runtime 静态 import。
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const OUT_DIR = resolve(ROOT, 'src/generated');
const OUT_FILE = resolve(OUT_DIR, 'sitemap-content.ts');

const SOURCES = [
  { input: 'public/robots.txt', exportName: 'ROBOTS_TXT' },
  { input: 'public/sitemap-image.xml', exportName: 'SITEMAP_IMAGE_XML' },
];

if (!existsSync(OUT_DIR)) {
  mkdirSync(OUT_DIR, { recursive: true });
}

const lines = [
  '// AUTO-GENERATED by scripts/generate-sitemap-content.mjs',
  '// Do not edit by hand — re-run the script to update.',
  '',
];

for (const { input, exportName } of SOURCES) {
  const abs = resolve(ROOT, input);
  if (!existsSync(abs)) {
    console.warn(`[gen-sitemap] SKIP: ${input} not found`);
    continue;
  }
  const content = readFileSync(abs, 'utf-8');
  // Use JSON.stringify to safely embed the string (handles escapes, quotes, newlines)
  const escaped = JSON.stringify(content);
  lines.push(`export const ${exportName}: string = ${escaped};`);
  lines.push('');
}

writeFileSync(OUT_FILE, lines.join('\n'), 'utf-8');
console.log(`[gen-sitemap] wrote: ${OUT_FILE}`);
