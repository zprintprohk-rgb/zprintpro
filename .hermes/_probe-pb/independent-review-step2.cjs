'use strict';
/**
 * 交付層獨立複核 Step 2（不採信專項單元自檢）
 * 最高風險兩項: ① 數值零改動 ② diff 只動字串值
 * 另複核: en/ja CJK 歸零 / zh-hk 簡體 / 檔頭未被手搓 / 確定性
 */
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const ROOT = 'F:\\zprintpro-nextjs';
const BAK = path.join(ROOT, '.hermes', '_bak-pricedata-20260918');
const NEW = path.join(ROOT, 'src', 'lib', 'price-data.generated.ts');

/* 找備份中的舊版 */
const cands = fs.readdirSync(BAK).filter(f => /price-data.*\.(ts|bak|orig|before)$/i.test(f) || /price-data/i.test(f));
console.log('備份目錄內容:', fs.readdirSync(BAK).join(' | '));

const readOld = () => {
  // 精確鎖定: price-data.generated.ts.before (不可誤取 gen-price-data.mjs.before)
  const exact = ['price-data.generated.ts.before', 'price-data.generated.ts.auto-prev'];
  for (const c of exact) {
    const p = path.join(BAK, c);
    if (fs.existsSync(p)) {
      const s = fs.readFileSync(p, 'utf8');
      if (s.includes('PRICE_TABLE_MAP')) return { name: c + ' (' + fs.statSync(p).size + ' B)', s };
    }
  }
  try {
    return { name: '(git HEAD)', s: execFileSync('git', ['show', 'HEAD:src/lib/price-data.generated.ts'], { cwd: ROOT, encoding: 'utf8', maxBuffer: 1 << 28 }) };
  } catch (e) { return null; }
};
const old = readOld();
const nw = fs.readFileSync(NEW, 'utf8');
if (!old) { console.log('❌ 找不到舊版可比對'); process.exit(1); }
console.log('比對基準: ' + old.name + ' (' + old.s.length + ' B) vs 現行 (' + nw.length + ' B)');

/* ① 數值 token 序列比對 */
const numTokens = s => (s.match(/-?\d+(?:\.\d+)?/g) || []);
const a = numTokens(old.s), b = numTokens(nw);
let firstDiff = -1;
for (let i = 0; i < Math.max(a.length, b.length); i++) if (a[i] !== b[i]) { firstDiff = i; break; }
console.log('\n① 數值零改動:');
console.log('   舊 '+a.length+' 個 token / 新 '+b.length+' 個 token');
console.log('   首個差異位置: ' + (firstDiff < 0 ? '無 (完全一致 ✅)' : firstDiff + ' → 舊=' + a[firstDiff] + ' 新=' + b[firstDiff]));
if (firstDiff < 0) console.log('   總量一致: ' + (a.length === b.length));
// 關鍵價格量總和
const sum = arr => arr.map(Number).filter(Number.isFinite).reduce((x, y) => x + y, 0);
console.log('   數值總和 舊=' + sum(a).toFixed(2) + ' 新=' + sum(b).toFixed(2) + (Math.abs(sum(a) - sum(b)) < 1e-6 ? '  ✅' : '  ★不一致'));

/* ② 逐行 diff 性質: 只允許字串值行變動 */
const ol = old.s.split('\n'), nl = nw.split('\n');
console.log('\n② diff 性質 (逐行):');
console.log('   行數 舊=' + ol.length + ' 新=' + nl.length + (ol.length === nl.length ? ' ✅ 同長' : ' ★不同長'));
let changed = 0, nonStringLine = 0;
const samples = [];
for (let i = 0; i < Math.min(ol.length, nl.length); i++) {
  if (ol[i] !== nl[i]) {
    changed++;
    const okShape = /^\s*"(zh-hk|en|ja)":\s*".*",?\s*$/.test(ol[i]) && /^\s*"(zh-hk|en|ja)":\s*".*",?\s*$/.test(nl[i]);
    if (!okShape) { nonStringLine++; if (samples.length < 6) samples.push('L' + (i + 1) + ' 舊: ' + ol[i].trim().slice(0, 70) + '  ||  新: ' + nl[i].trim().slice(0, 70)); }
  }
}
console.log('   變動行數: ' + changed);
console.log('   非「語系字串值」形狀的變動行: ' + nonStringLine + (nonStringLine === 0 ? ' ✅' : ' ★'));
samples.forEach(s => console.log('     ' + s));

/* ③ 污染現況 (交付層自掃, 獨立於專項單元腳本) */
const CJK = /[\u3400-\u4dbf\u4e00-\u9fff]/;
const KANA = /[\u3040-\u30ff]/;
const SIMP = '们个为无与书车门问说时东华产国学体线标签页单价简边发对开关电话后从这来让给还两么义应该当经历众飞机场击视频听读写语词记录买卖贵贱农医乐儿长张纸费计认识种类别离继续断错谁务动员双画数际专亚达诺论约伦纽专';
// ★ ja 專用窄集: 只收「日文中不存在該字形」者 —— 排除日文新字體 (学数点双画国体来与当医断错写言…)
//   (2026-09-18 教訓: 直接把 zh-hk 寬集套 ja 會誤報 19 處真日文)
const SIMP_JA = '们个为无书车门问说时东华产义应该让给还两么众飞机场击视频听读语词记录买卖贵贱农医乐儿长张费认识种类别离继续绝对单际专亚达诺论约伦纽';
const SIMP_ZH = SIMP_JA + '与国体线标签页价简边发对开关电话后从这来当经历双画数';
const RE = /^\s*"(zh-hk|en|ja)":\s*"((?:[^"\\]|\\.)*)",?\s*$/;
let enCJK = 0, jaNoKana = 0, zhSimp = 0, jaSimp = 0, fields = 0;
const jaSimpHits = new Set();
for (const l of nl) {
  const m = l.match(RE); if (!m) continue;
  fields++;
  const loc = m[1], v = m[2];
  if (loc === 'en' && CJK.test(v)) enCJK++;
  if (loc === 'ja' && CJK.test(v) && !KANA.test(v)) jaNoKana++;
  if (loc === 'zh-hk' && new RegExp('[' + SIMP_ZH + ']').test(v)) zhSimp++;
  if (loc === 'ja') {
    const h = [...v.matchAll(new RegExp('[' + SIMP_JA + ']', 'g'))].map(x => x[0]);
    if (h.length) { jaSimp++; h.forEach(c => jaSimpHits.add(c)); }
  }
}
console.log('\n③ 污染 (交付層自掃 ' + fields + ' 個語系欄位):');
console.log('   en 含漢字        : ' + enCJK + (enCJK === 0 ? ' ✅' : ' ★'));
console.log('   ja 有漢字零假名  : ' + jaNoKana + (jaNoKana === 0 ? ' ✅' : ' ★'));
console.log('   zh-hk 含簡體專用 : ' + zhSimp + (zhSimp === 0 ? ' ✅' : ' ★'));
console.log('   ja 含簡體專用(窄集): ' + jaSimp + (jaSimp === 0 ? ' ✅' : ' ★ 命中字: ' + [...jaSimpHits].join('')));

/* ④ 檔頭聲明 */
console.log('\n④ 生成檔聲明: ' + (nw.includes('Generated by scripts/gen-price-data.mjs') ? '保留 ✅' : '★ 遺失'));
console.log('   BOM=' + (fs.readFileSync(NEW)[0] === 0xEF) + ' CRLF=' + /\r\n/.test(nw));
