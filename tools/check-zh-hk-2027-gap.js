const data = require('../src/data/blog-data/zh-hk.json');
const p = data['2027-monthly-calendar-printing-timetable'];
const c = p.content;
console.log('=== zh-hk 2027 月历现状 ===');
console.log('Total length:', c.length);
const h2 = (c.match(/<h2[^>]*>([^<]+)<\/h2>/g) || []).length;
const tables = (c.match(/<table[^>]*>/g) || []).length;
const internalLinks = [...new Set([...c.matchAll(/href="(\/[^"]+|https:\/\/zprintpro\.com[^"]+)"/g)].map(m => m[1]))];
const qa = [...c.matchAll(/<strong>Q\d+[：:][^<]+<\/strong>/g)];
const callouts = (c.match(/<div class="[^"]*(?:callout|info-box|highlight|note|bg-blue|bg-gray)[^"]*"/g) || []).length;
console.log('H2 段:', h2, '(目标 9)');
console.log('Q&A:', qa.length, '(目标 4)');
console.log('内链:', internalLinks.length, '(目标 5)');
console.log('Tables:', tables, '(目标 2)');
console.log('Callouts:', callouts, '(目标 2)');
console.log('---');
const gaps = [];
if (h2 < 9) gaps.push('  段差: ' + (9 - h2) + ' 段');
if (qa.length < 4) gaps.push('  FAQ 差: ' + (4 - qa.length) + ' 题');
if (internalLinks.length < 5) gaps.push('  内链差: ' + (5 - internalLinks.length) + ' 条');
if (tables < 2) gaps.push('  Table 差: ' + (2 - tables) + ' 个');
if (callouts < 2) gaps.push('  Callout 差: ' + (2 - callouts) + ' 个');
if (gaps.length === 0) console.log('全部达标 100%!');
else console.log('缺口:\n' + gaps.join('\n'));
